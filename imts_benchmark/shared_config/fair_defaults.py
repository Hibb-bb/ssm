"""Centralised fair-comparison defaults shared by all IMTS benchmark trainers
(Mamba-MV, RoMAE, mTAN, ContiFormer, S5).

Any knob listed here MUST be identical across all models. Model-specific
architectural knobs (d_model, depth, etc.) are set by each model's own
train script so that parameter counts can be matched within +/-10%.

v2 (phase 2 onward): regimes switched from the deprecated sparse_/nogap_
grid (generated by generate_longgap_multisin.py) to the correct convex-mix
multisin irregularity grid (generated by generate_multivariate_sinusodial_data.py,
ported from the colleague's reference at ssm_model/ssm/mamba_experiments/
dataset_generation/).
"""

from __future__ import annotations

import argparse
from pathlib import Path


DATA_ROOT_DEFAULT = (
    "/projects/b1094/StarEmbed/skai_universal_forecaster/src/train/"
    "moirai/uni2ts_hongyu/ssm_dk/data_correct"
)
LOG_ROOT_DEFAULT = (
    "/projects/b1094/StarEmbed/skai_universal_forecaster/output/log/imts_benchmark_v2"
)

HISTORY = 8.0
T_MAX = 10.0
N_VARS = 3

LR = 5e-4
WEIGHT_DECAY = 0.01
NUM_WARMUP_STEPS = 100
NUM_TRAINING_STEPS = 1600
MAX_EPOCHS = 200
PATIENCE = 50  # bumped from 20 after observing mTAN/S5/RoMAE being early-stopped
               # at ~25% of the cosine schedule (2026-04-22 Phase 2 diagnosis).
GRADIENT_CLIP_VAL = 1.0
TRAIN_BATCH_SIZE = 128
VAL_BATCH_SIZE = 32
NUM_WORKERS = 2

SEEDS = (1, 2, 3, 4, 5)
REGIMES = (
    "multisin_regular",
    "multisin_low_irreg",
    "multisin_med_irreg",
    "multisin_high_irreg",
)


def add_fair_args(parser: argparse.ArgumentParser) -> argparse.ArgumentParser:
    """Attach the fair-comparison knobs. Both trainers call this."""
    parser.add_argument("--data_root", type=str, default=DATA_ROOT_DEFAULT)
    parser.add_argument("--regime", type=str, required=True, choices=REGIMES)
    parser.add_argument("--seed", type=int, required=True)
    parser.add_argument("--output_dir", type=str, required=True)

    parser.add_argument("--lr", type=float, default=LR)
    parser.add_argument("--weight_decay", type=float, default=WEIGHT_DECAY)
    parser.add_argument("--num_warmup_steps", type=int, default=NUM_WARMUP_STEPS)
    parser.add_argument("--num_training_steps", type=int, default=NUM_TRAINING_STEPS)
    parser.add_argument("--max_epochs", type=int, default=MAX_EPOCHS)
    parser.add_argument("--patience", type=int, default=PATIENCE)
    parser.add_argument("--gradient_clip_val", type=float, default=GRADIENT_CLIP_VAL)

    parser.add_argument("--train_batch_size", type=int, default=TRAIN_BATCH_SIZE)
    parser.add_argument("--val_batch_size", type=int, default=VAL_BATCH_SIZE)
    parser.add_argument("--num_workers", type=int, default=NUM_WORKERS)
    # accumulate_grad_batches: effective_batch = train_batch_size * accumulate_grad_batches.
    # Default 1 (no accumulation). Models that OOM at the shared train_batch_size
    # should drop to a smaller batch AND bump this so the effective optimization
    # regime stays identical across models (see baseline_spec_contiformer.md).
    parser.add_argument("--accumulate_grad_batches", type=int, default=1)

    parser.add_argument("--history", type=float, default=HISTORY)
    parser.add_argument("--t_max", type=float, default=T_MAX)
    parser.add_argument("--n_vars", type=int, default=N_VARS)

    # fp32 everywhere: matches the canonical univariate Mamba baseline
    # (MambaIrregularBlock forces dt to fp32 internally, which trips the CUDA
    # selective-scan kernel's dtype-match check under bf16-mixed autocast).
    parser.add_argument("--precision", type=str, default="32-true")
    return parser


def regime_data_path(data_root: str, regime: str) -> Path:
    return Path(data_root) / regime
